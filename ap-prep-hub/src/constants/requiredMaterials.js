/** True when this course has a required list. */
export const hasRequiredMaterials = (subject) => Boolean(MATERIALS[subjectName(subject)]);

/**
 * A prompt block naming the course's required materials, or '' for courses
 * without one. `compact` joins the lists on one line each (for the tutor,
 * whose prompt is sent with every message).
 */
export function requiredMaterialsFor(subject, { compact = false } = {}) {
  const lists = MATERIALS[subjectName(subject)];
  if (!lists) return '';
  const body = lists.map(([title, items]) => (compact
    ? `${title}: ${items.join('; ')}`
    : `${title}:\n${items.map((x) => `- ${x}`).join('\n')}`)).join(compact ? '\n' : '\n\n');
  return `REQUIRED COURSE MATERIALS (current College Board course description). Exam questions draw on these: use them by name, cite them accurately, and do not present other texts as required.\n${body}`;
}
